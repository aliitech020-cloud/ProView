"""Render the ProVixel app icon (run once; needs the Inter font installed).

Writes assets/provixel.ico, assets/provixel.png and proview/app_icon_data.py
(base64 PNGs embedded in the app so it looks the same on every PC).
"""
import base64
import io
import os
import sys

from PySide6.QtCore import QBuffer, QRectF, Qt
from PySide6.QtGui import QColor, QFont, QFontMetricsF, QGuiApplication, QImage, QLinearGradient, QPainter, QPainterPath, QPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIZES = (16, 24, 32, 48, 64, 128, 256)


def font(weight, px):
    f = QFont("Inter")
    f.setWeight(weight)
    f.setPixelSize(max(1, int(px)))
    return f


def fit_text(text, weight, max_w, max_px):
    px = max_px
    while px > 4 and QFontMetricsF(font(weight, px)).horizontalAdvance(text) > max_w:
        px -= 0.5
    return font(weight, px)


def render(size):
    S = 256.0
    img = QImage(size, size, QImage.Format_ARGB32)
    img.fill(Qt.transparent)
    p = QPainter(img)
    p.setRenderHint(QPainter.Antialiasing)
    p.setRenderHint(QPainter.TextAntialiasing)
    p.scale(size / S, size / S)

    # background tile
    r = QRectF(8, 8, 240, 240)
    path = QPainterPath()
    path.addRoundedRect(r, 54, 54)
    g = QLinearGradient(0, 0, S, S)
    g.setColorAt(0.0, QColor("#2b6ff2"))
    g.setColorAt(0.55, QColor("#1a3f9e"))
    g.setColorAt(1.0, QColor("#0b1a45"))
    p.fillPath(path, g)
    gloss = QLinearGradient(0, 8, 0, 128)
    gloss.setColorAt(0.0, QColor(255, 255, 255, 46))
    gloss.setColorAt(1.0, QColor(255, 255, 255, 0))
    p.fillPath(path, gloss)
    p.setPen(QPen(QColor(255, 255, 255, 40), 2))
    p.drawPath(path)

    # voxel accent: three small cubes (the "Vixel" in the name)
    def cube(x, y, s, alpha):
        p.setPen(Qt.NoPen)
        p.setBrush(QColor(110, 225, 255, alpha))
        p.drawRoundedRect(QRectF(x, y, s, s), s * 0.22, s * 0.22)

    if size >= 48:
        cube(184, 34, 18, 255)
        cube(206, 34, 18, 150)
        cube(206, 56, 18, 90)

    white = QColor(255, 255, 255)
    cyan = QColor(140, 225, 255)
    if size >= 64:
        # two lines: "Pro" over a big "Vixel"
        f1 = fit_text("Pro", QFont.Medium, 150, 62)
        p.setFont(f1)
        p.setPen(cyan)
        p.drawText(QRectF(30, 52, 200, 70), Qt.AlignLeft | Qt.AlignBottom, "Pro")
        f2 = fit_text("Vixel", QFont.ExtraBold, 196, 92)
        p.setFont(f2)
        p.setPen(white)
        p.drawText(QRectF(28, 112, 210, 100), Qt.AlignLeft | Qt.AlignVCenter, "Vixel")
    else:
        # small sizes: monogram
        f = fit_text("PV", QFont.Black, 190, 150)
        p.setFont(f)
        p.setPen(white)
        p.drawText(QRectF(8, 8, 240, 240), Qt.AlignCenter, "PV")
    p.end()
    return img


def png_bytes(img):
    buf = QBuffer()
    buf.open(QBuffer.WriteOnly)
    img.save(buf, "PNG")
    return bytes(buf.data())


def main():
    app = QGuiApplication(sys.argv)  # noqa: F841
    pngs = {s: png_bytes(render(s)) for s in SIZES}
    os.makedirs(os.path.join(ROOT, "assets"), exist_ok=True)
    with open(os.path.join(ROOT, "assets", "provixel.png"), "wb") as fh:
        fh.write(pngs[256])
    from PIL import Image

    imgs = [Image.open(io.BytesIO(pngs[s])).convert("RGBA") for s in sorted(SIZES, reverse=True)]
    imgs[0].save(os.path.join(ROOT, "assets", "provixel.ico"), sizes=[(s, s) for s in sorted(SIZES, reverse=True)],
                 append_images=imgs[1:])
    with open(os.path.join(ROOT, "proview", "app_icon_data.py"), "w") as fh:
        fh.write('"""ProVixel app icon, generated by tools/make_icon.py - do not edit."""\n\nPNG_BASE64 = {\n')
        for s in SIZES:
            fh.write(f'    {s}: "{base64.b64encode(pngs[s]).decode()}",\n')
        fh.write("}\n")
    print("ok")


if __name__ == "__main__":
    main()
